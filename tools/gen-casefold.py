"""Generate crates/hexicon-vm/src/casefold.rs from the reference VM's
Unicode case tables (tads3/derived/vmuni_cs.cpp).

Usage: python tools/gen-casefold.py <path to vmuni_cs.cpp>
"""

import re
import sys

with open(sys.argv[1], encoding="latin-1") as source_file:
    source = source_file.read()

# The expansion pool: runs of code points, each ended by a zero.
pool_text = source[source.index("static wchar_t case_expansion[] =") :]
pool_text = pool_text[: pool_text.index("};")]
pool_text = re.sub(r"/\*.*?\*/", "", pool_text)
pool = [int(n, 16) for n in re.findall(r"0x([0-9a-fA-F]+)", pool_text)]

# The pages: 128 characters each, with offsets into the pool.
pages = {}
for match in re.finditer(
    r"static case_table (case_pg_\w+)\[128\] =\s*\{(.*?)\n\};", source, re.DOTALL
):
    rows = re.findall(
        r"\{\s*0x(\w+),\s*0x(\w+),\s*0x(\w+),\s*0x(\w+)\s*\}", match.group(2)
    )
    assert len(rows) == 128, match.group(1)
    pages[match.group(1)] = [int(row[3], 16) for row in rows]

table_text = source[source.index("case_tab[") :]
table_text = table_text[table_text.index("{") + 1 : table_text.index("};")]
table_text = re.sub(r"/\*.*?\*/", "", table_text)
table = [name.strip() for name in table_text.split(",") if name.strip()]

entries = []
for page_index, name in enumerate(table):
    if name == "0":
        continue
    for low, offset in enumerate(pages[name]):
        if offset == 0:
            continue
        end = pool.index(0, offset)
        entries.append((page_index * 128 + low, pool[offset:end]))

out = [
    "//! Unicode case folding: the form of a character used to compare text",
    "//! without regard to case. One character can fold to several.",
    "//!",
    "//! Generated by `tools/gen-casefold.py` from the reference VM's tables, so",
    "//! that folded text is the same here as there. Do not edit.",
    "",
    "/// Each character that folds to something other than itself, in order,",
    "/// with what it folds to.",
    "#[rustfmt::skip]",
    f"static FOLD: [(u16, &str); {len(entries)}] = [",
]
for code, expansion in entries:
    text = "".join(f"\\u{{{c:x}}}" for c in expansion)
    out.append(f'    (0x{code:04x}, "{text}"),')
out += [
    "];",
    "",
    "/// What a character folds to, or `None` if it folds to itself.",
    "pub(crate) fn fold(c: char) -> Option<&'static str> {",
    "    let code = u16::try_from(u32::from(c)).ok()?;",
    "    FOLD.binary_search_by_key(&code, |&(from, _)| from)",
    "        .ok()",
    "        .map(|index| FOLD[index].1)",
    "}",
    "",
]
with open(
    "crates/hexicon-vm/src/casefold.rs", "w", encoding="utf-8", newline="\n"
) as output_file:
    output_file.write("\n".join(out))
print(len(entries), "entries")
