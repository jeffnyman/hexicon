"""Generate crates/hexicon-vm/src/chartype.rs from the reference VM's
Unicode character type table (tads3/derived/vmuni_cs.cpp).

Usage: python tools/gen-chartype.py <path to vmuni_cs.cpp>

The reference's table has a type for each of the 65,536 characters of the
Basic Multilingual Plane, two to a byte. Most characters have the same type
as their neighbors, so the generated table lists only where the type
changes.
"""

import re
import sys

with open(sys.argv[1], encoding="latin-1") as source_file:
    source = source_file.read()

NAMES = [
    "UNDEF",
    "ALPHA",
    "UPPER",
    "TITLE",
    "LOWER",
    "DIGIT",
    "SPACE",
    "VSPAC",
    "PUNCT",
    "OTHER",
]
VARIANTS = [
    "Undefined",
    "Alpha",
    "Upper",
    "Title",
    "Lower",
    "Digit",
    "Space",
    "VSpace",
    "Punct",
    "Other",
]

text = source[source.index("static const unsigned char chartype[32768] =") :]
text = text[text.index("{") + 1 : text.index("};")]
text = re.sub(r"/\*.*?\*/", "", text)
pairs = re.findall(r"\(T3_CTYPE_(\w+) << 4\) \| T3_CTYPE_(\w+)", text)
assert len(pairs) == 32768, len(pairs)

# Each byte holds the type of an even character in its low half and of the
# odd character after it in its high half.
types = []
for high, low in pairs:
    types.append(NAMES.index(low))
    types.append(NAMES.index(high))

runs = []
for code, kind in enumerate(types):
    if not runs or runs[-1][1] != kind:
        runs.append((code, kind))

out = []
out.append(
    "//! The type of each character: letter, digit, space, punctuation, and so on."
)
out.append("//!")
out.append("//! Generated by `tools/gen-chartype.py` from the reference VM's table, so")
out.append("//! that a character is the same kind of thing here as there. Do not edit.")
out.append("")
out.append("/// What kind of character one is. Each character has exactly one type.")
out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
out.append("pub(crate) enum CharType {")
docs = [
    "Not a character.",
    "A letter with no case.",
    "A capital letter.",
    "A title-case letter.",
    "A small letter.",
    "A digit.",
    "A space within a line.",
    "A space that ends a line.",
    "A punctuation mark.",
    "Anything else, such as a symbol or a control character.",
]
for variant, doc in zip(VARIANTS, docs):
    out.append(f"    /// {doc}")
    out.append(f"    {variant},")
out.append("}")
out.append("")
out.append("use CharType::{")
out.append(
    "    Alpha as A, Digit as D, Lower as L, Other as O, Punct as P, Space as S, Title as T,"
)
out.append("    Undefined as N, Upper as U, VSpace as V,")
out.append("};")
out.append("")
SHORT = ["N", "A", "U", "T", "L", "D", "S", "V", "P", "O"]
out.append("/// Where the type changes: each entry is the first character of a run")
out.append("/// of characters of one type, which lasts until the next entry.")
out.append("#[rustfmt::skip]")
out.append(f"static RUNS: [(u16, CharType); {len(runs)}] = [")
line = "   "
for code, kind in runs:
    item = f" (0x{code:04x}, {SHORT[kind]}),"
    if len(line) + len(item) > 96:
        out.append(line)
        line = "   "
    line += item
out.append(line)
out.append("];")
out.append("")
out.append("""/// The type of a character. The reference's table stops at U+FFFF; past
/// it, where the reference has no answer, the standard library's idea of
/// the character stands in.
pub(crate) fn char_type(c: char) -> CharType {
    let Ok(code) = u16::try_from(u32::from(c)) else {
        return if c.is_uppercase() {
            U
        } else if c.is_lowercase() {
            L
        } else if c.is_alphabetic() {
            A
        } else if c.is_numeric() {
            D
        } else {
            O
        };
    };
    let index = RUNS.partition_point(|&(start, _)| start <= code);
    RUNS[index - 1].1
}

/// A letter of any case, or of none.
pub(crate) fn is_alpha(c: char) -> bool {
    matches!(char_type(c), A | U | T | L)
}

/// A capital or title-case letter.
pub(crate) fn is_upper(c: char) -> bool {
    matches!(char_type(c), U | T)
}

/// A small letter.
pub(crate) fn is_lower(c: char) -> bool {
    char_type(c) == L
}

/// A digit.
pub(crate) fn is_digit(c: char) -> bool {
    char_type(c) == D
}

/// A space within a line.
pub(crate) fn is_space(c: char) -> bool {
    char_type(c) == S
}

/// A space that ends a line.
pub(crate) fn is_vspace(c: char) -> bool {
    char_type(c) == V
}

/// A punctuation mark. Symbols, such as `+` and `>`, are not.
pub(crate) fn is_punct(c: char) -> bool {
    char_type(c) == P
}""")

with open(
    "crates/hexicon-vm/src/chartype.rs", "w", encoding="utf-8", newline="\n"
) as out_file:
    out_file.write("\n".join(out) + "\n")
print(len(runs), "runs")
