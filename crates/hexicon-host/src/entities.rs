/// The character a named entity stands for.
pub fn lookup(name: &str) -> Option<char> {
    ENTITIES
        .binary_search_by(|(entry, _)| (*entry).cmp(name))
        .ok()
        .and_then(|index| char::from_u32(ENTITIES[index].1))
}
