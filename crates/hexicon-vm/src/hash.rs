//! The SHA-256 and MD5 hash functions, for the `sha256` and `digestMD5`
//! methods of String and ByteArray.
//!
//! Neither is here for security. Programs use them as checksums and to
//! talk to services that ask for them, and the answers have to be the
//! standard ones.

/// Write bytes in hexadecimal, with capital letters as the reference VM
/// writes a hash.
pub(crate) fn hex(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    for &byte in bytes {
        for nibble in [byte >> 4, byte & 15] {
            let digit = char::from_digit(nibble.into(), 16).unwrap_or('0');
            out.push(digit.to_ascii_uppercase());
        }
    }
    out
}

/// Pad a message the way both functions do: a one bit, zeros, and the
/// length in bits as a 64-bit integer.
fn padded(data: &[u8], big_endian_length: bool) -> Vec<u8> {
    let bits = (data.len() as u64).wrapping_mul(8);
    let mut message = data.to_vec();
    message.push(0x80);
    while message.len() % 64 != 56 {
        message.push(0);
    }
    if big_endian_length {
        message.extend_from_slice(&bits.to_be_bytes());
    } else {
        message.extend_from_slice(&bits.to_le_bytes());
    }
    message
}

