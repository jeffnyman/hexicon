/// The type of a character. The reference's table stops at U+FFFF; past
/// it, where the reference has no answer, the standard library's idea of
/// the character stands in.
pub(crate) fn char_type(c: char) -> CharType {
    let Ok(code) = u16::try_from(u32::from(c)) else {
        return if c.is_uppercase() {
            U
        } else if c.is_lowercase() {
            L
        } else if c.is_alphabetic() {
            A
        } else if c.is_numeric() {
            D
        } else {
            O
        };
    };
    let index = RUNS.partition_point(|&(start, _)| start <= code);
    RUNS[index - 1].1
}

/// A letter of any case, or of none.
pub(crate) fn is_alpha(c: char) -> bool {
    matches!(char_type(c), A | U | T | L)
}

/// A capital or title-case letter.
pub(crate) fn is_upper(c: char) -> bool {
    matches!(char_type(c), U | T)
}

/// A small letter.
pub(crate) fn is_lower(c: char) -> bool {
    char_type(c) == L
}

/// A digit.
pub(crate) fn is_digit(c: char) -> bool {
    char_type(c) == D
}

/// A space within a line.
pub(crate) fn is_space(c: char) -> bool {
    char_type(c) == S
}

/// A space that ends a line.
pub(crate) fn is_vspace(c: char) -> bool {
    char_type(c) == V
}

/// A punctuation mark. Symbols, such as `+` and `>`, are not.
pub(crate) fn is_punct(c: char) -> bool {
    char_type(c) == P
}
